function familleCode(code) {
  const l = code[0], d = code[1], s = code[2];
  const constructeur = (d === '1' || (l === 'P' && d === '3' && parseInt(s, 16) < 4));
  if (l === 'P') {
    const sys = {
      '0': "Mesure d'air et de carburant, dépollution", '1': "Mesure d'air et de carburant",
      '2': "Injection (circuit des injecteurs)", '3': "Allumage et ratés d'allumage",
      '4': "Dépollution auxiliaire (EGR, catalyseur, vapeurs)", '5': "Vitesse, ralenti et entrées auxiliaires",
      '6': "Calculateur et sorties auxiliaires", '7': "Boîte de vitesses", '8': "Boîte de vitesses", '9': "Boîte de vitesses",
      'A': "Propulsion hybride", 'B': "Propulsion hybride", 'C': "Propulsion hybride"
    }[s] || "Moteur et transmission";
    return (constructeur ? "Code propre au constructeur — " : "") + sys;
  }
  const base = { C: "Châssis (freinage, direction, suspension)", B: "Carrosserie (airbags, confort, éclairage)", U: "Réseau de communication entre calculateurs" }[l];
  return (constructeur ? "Code propre au constructeur — " : "") + base;
}
