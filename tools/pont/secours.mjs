#!/usr/bin/env node
/* PONT DE SECOURS — gratuit, sans Cloudflare (Kevin 25.10.2026 : « trouve une solution gratuite pour débloquer le blocage du pont »).
 * Cause du blocage (25.10, mesuré) : le quota GRATUIT de lecture de D1 (5 M lignes/jour pour tout le compte) est dépassé → code 7500
 * « exceeded D1's free tier daily row read limit », même une lecture d'UNE ligne ou un CREATE INDEX est refusé jusqu'à minuit UTC.
 * Pendant ce temps le pont vit dans la discussion privée n° 5236 du dépôt CMCteams (commentaires = messages ; aucun quota à nous).
 *   node tools/pont/secours.mjs ecrire <de> <à> "<sujet>" "<corps>"     écrit un message
 *   node tools/pont/secours.mjs lire <ton-nom> [depuis-l-id]            lit ce qui t'est adressé (ou « toutes »)
 *   node tools/pont/secours.mjs rejouer [depuis-l-id]                   imprime le SQL à passer à D1 une fois revenu (sans doublon)
 * Jamais de secret : les textes qui ressemblent à une clé, un jeton ou un code sont refusés. Lenovo : mêmes messages avec le connecteur GitHub. */
import { execFileSync } from 'node:child_process';

export const DEPOT = '9r4rxssx64-creator/CMCteams';
export const FIL = 5236;
export const SECRET = /(sk-[A-Za-z0-9_-]{16,}|gh[pousr]_[A-Za-z0-9]{20,}|AKIA[0-9A-Z]{12,}|eyJ[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]{10,}|bearer\s+[A-Za-z0-9._-]{20,}|\b[0-9a-f]{40,}\b|\b[0-9a-f]{64}\b|\/__admin\/[a-z]+\?[^\s]*(?:token|pass)=)/i;

export function formater(de, a, sujet, corps) {
  const t = `${de} ${a} ${sujet} ${corps}`;
  if (SECRET.test(t)) throw new Error('refusé : le texte ressemble à un secret (clé, jeton, empreinte, lien d’accès) — le pont n’en porte jamais');
  if (!/^[a-z0-9._-]{2,40}$/i.test(de) || !/^[a-z0-9._;-]{2,80}$/i.test(a)) throw new Error('de / à : un nom de branche (lettres, chiffres, - _ .)');
  return `**${de} → ${a}** · ${String(sujet).replace(/\n/g, ' ').slice(0, 160)}\n\n${corps}`;
}
export function analyser(c) {
  const brut = String(c.body || '').replace(/\n+---\n_Generated by[\s\S]*$/, '');   // pied ajouté par certains outils
  const m = /^\*\*([a-z0-9._-]+) → ([a-z0-9._;-]+)\*\* · ([^\n]*)\n\n([\s\S]*)$/i.exec(brut);
  return m ? { id: c.id, ts: Date.parse(c.created_at) || 0, de: m[1], a: m[2], sujet: m[3], corps: m[4] } : null;
}
export const pourMoi = (msg, nom) => msg.de !== nom && (msg.a === 'toutes' || ('; ' + msg.a.split(';').join('; ') + ';').includes('; ' + nom + ';'));
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";
export function sqlRejeu(msg) {
  const repere = `[secours#${msg.id}]`;
  return `INSERT INTO messages (ts,de,a,sujet,corps,lu_par) SELECT ${msg.ts},${q(msg.de)},${q(msg.a)},${q(msg.sujet + ' ' + repere)},${q(msg.corps)},'' WHERE NOT EXISTS (SELECT 1 FROM messages WHERE sujet LIKE ${q('%' + repere)});`;
}

const gh = (...args) => JSON.parse(execFileSync('gh', ['api', ...args], { encoding: 'utf8', maxBuffer: 20 * 1024 * 1024 }));
function commentaires(depuis = 0) {
  const tous = []; for (let p = 1; p < 20; p++) { const l = gh(`repos/${DEPOT}/issues/${FIL}/comments?per_page=100&page=${p}`); tous.push(...l); if (l.length < 100) break; }
  return tous.map(analyser).filter((m) => m && m.id > depuis);
}
if (process.argv[1] && /(^|[\\/])secours\.mjs$/.test(process.argv[1])) {
  const [cmd, ...a] = process.argv.slice(2);
  if (cmd === 'ecrire') {
    const [de, vers, sujet, ...corps] = a; const body = formater(de, vers, sujet || '', corps.join(' '));
    const r = gh('-X', 'POST', `repos/${DEPOT}/issues/${FIL}/comments`, '-f', `body=${body}`);
    console.log(`✔ écrit au pont de secours (commentaire ${r.id})`);
  } else if (cmd === 'lire') {
    const nom = a[0]; if (!nom) { console.error('lire <ton-nom> [depuis-l-id]'); process.exit(2); }
    const l = commentaires(Number(a[1] || 0)).filter((m) => pourMoi(m, nom));
    for (const m of l) console.log(`#${m.id} · ${new Date(m.ts).toISOString().slice(11, 16)} · ${m.de} → ${m.a} · ${m.sujet}\n${m.corps}\n`);
    console.log(`— ${l.length} message(s) pour ${nom} (dernier id : ${l.length ? l[l.length - 1].id : a[1] || 0})`);
  } else if (cmd === 'rejouer') {
    for (const m of commentaires(Number(a[0] || 0))) console.log(sqlRejeu(m));
  } else { console.error('ecrire | lire | rejouer — voir l’en-tête du fichier'); process.exit(2); }
}
